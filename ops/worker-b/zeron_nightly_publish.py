"""Deterministic B checkpoint publication. No model requests or checkout mutation."""
import base64
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import subprocess
import time

REPO = 'Umbral-lab/zeron'
ACTOR = 'umbral-labs-dev[bot]'
HELPER = Path('/home/jetson/.hermes/profiles/zeron/scripts/zeron-github-app.py')
IDENTITY = {'name': 'Umbral Agent',
            'email': '340979744+umbral-labs-dev[bot]@users.noreply.github.com'}


def sanitize(text):
    text = re.sub(r'\x1b\[[0-?]*[ -/]*[@-~]', '', str(text))
    text = re.sub(r'gh[pousr]_[A-Za-z0-9_]{20,}', '[REDACTED]', text)
    text = re.sub(r'(?i)(bearer\s+)[A-Za-z0-9._-]+', r'\1[REDACTED]', text)
    if '-----BEGIN ' in text and 'PRIVATE KEY-----' in text:
        raise ValueError('Refusing to publish possible private key material')
    return text[:40000]


def checkpoint(result):
    """Task completion is explicit; process exit zero is never sufficient."""
    text = str(result.get('final_response') or '')
    complete = (result.get('completed') is True and not result.get('failed')
                and re.search(r'^TASK_STATUS:\s*COMPLETE\s*$', text, re.MULTILINE) is not None)
    return {'status': 'complete' if complete else 'partial', 'report': sanitize(text),
            'reason': 'Explicit task completion' if complete else 'Incomplete or missing completion marker',
            'handoff_status': 'pending'}


def render(record, packet):
    report = sanitize(packet.get('report') or 'No final report was produced. Inspect the private run log; no completion is claimed.')
    return ('# Worker B nightly result — ' + record['date'] + '\n\n'
            '- Task status: **' + packet['status'].upper() + '**\n'
            '- Run: `' + record['run_id'] + '`\n'
            '- Reviewed source: `' + record['source'] + '`\n'
            '- Model attempts: ' + str(record.get('requests', 0)) + '\n'
            '- Reserved generated tokens (not measured usage): ' + str(record.get('reserved_generated', 0)) + '\n'
            '- Worker process exit: ' + str(record.get('returncode')) + '\n'
            '- Reason: ' + sanitize(packet.get('reason', 'No completion evidence')) + '\n'
            '- Evidence scope: model source inspection; no independent approval or runtime test is implied.\n'
            '- Publication: generated by the deterministic controller after model execution; no extra model request.\n\n'
            '## Preserved report\n\n' + report + '\n')


def api(method, path, payload, deadline):
    remaining = deadline - time.monotonic()
    if remaining < 3:
        raise TimeoutError('Publication deadline reached; checkpoint retained locally')
    command = ['python3', str(HELPER), 'api', '--method', method, path]
    if payload is not None:
        command += ['--input', '-']
    result = subprocess.run(command, input=json.dumps(payload) if payload is not None else None,
                            text=True, capture_output=True, timeout=min(30, remaining))
    if result.returncode:
        raise RuntimeError('GitHub publication request failed: ' + method + ' ' + path)
    return json.loads(result.stdout) if result.stdout.strip() else None


def publish(record, packet, deadline, call=api):
    """Publish fixed-path evidence, then verify exact content and target objects."""
    date, source = record['date'], record['source']
    if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', date) or not re.fullmatch(r'[0-9a-f]{40}', source):
        raise ValueError('Invalid run identifiers')
    prefix = 'repos/' + REPO
    branch = 'worker-b/audit-' + date
    path = 'docs/audits/' + date + '-worker-b.md'
    content = render(record, packet)
    # The final content checkpoint is local before any network side effect.
    base = call('GET', prefix + '/git/commits/' + source, None, deadline)
    tree = call('POST', prefix + '/git/trees', {'base_tree': base['tree']['sha'],
        'tree': [{'path': path, 'mode': '100644', 'type': 'blob', 'content': content}]}, deadline)
    stamp = datetime.now(timezone.utc).isoformat()
    commit = call('POST', prefix + '/git/commits', {
        'message': 'Record B nightly ' + packet['status'] + ' result for ' + date,
        'tree': tree['sha'], 'parents': [source],
        'author': dict(IDENTITY, date=stamp), 'committer': dict(IDENTITY, date=stamp)}, deadline)
    # Same-day admission prevents repeats. A ref collision fails closed; never force-update.
    call('POST', prefix + '/git/refs', {'ref': 'refs/heads/' + branch, 'sha': commit['sha']}, deadline)
    status = packet['status'].upper()
    title = 'B nightly ' + date + ': ' + status
    body = ('Task status: **' + status + '**.\n\nRun `' + record['run_id'] + '`, source `' + source
            + '`, result head `' + commit['sha'] + '`.\n\n' + content
            + '\n\nA: review the preserved evidence. Partial work is not approval or task acceptance. '
            'No model allowance was spent on this publication. Related automation: #4.\n')
    issue = call('POST', prefix + '/issues', {'title': title, 'body': body}, deadline)
    packet.update(issue_url=issue['html_url'], head=commit['sha'])
    pr_body = body + '\n\nTracking issue: ' + issue['html_url'] + '\n'
    pr = call('POST', prefix + '/pulls', {'title': title, 'head': branch, 'base': 'main',
        'body': pr_body, 'draft': packet['status'] != 'complete',
        'maintainer_can_modify': True}, deadline)
    packet['pr_url'] = pr['html_url']
    issue_body = body + '\n\nResult PR: ' + pr['html_url'] + '\n'
    call('PATCH', prefix + '/issues/' + str(issue['number']), {'body': issue_body}, deadline)
    # Read back authors, exact bodies, branch SHA and decoded artifact bytes.
    actual_issue = call('GET', prefix + '/issues/' + str(issue['number']), None, deadline)
    actual_pr = call('GET', prefix + '/pulls/' + str(pr['number']), None, deadline)
    actual_ref = call('GET', prefix + '/git/ref/heads/' + branch, None, deadline)
    artifact = call('GET', prefix + '/contents/' + path + '?ref=' + branch, None, deadline)
    if not (actual_issue['user']['login'] == ACTOR and actual_issue['body'] == issue_body
            and actual_pr['user']['login'] == ACTOR and actual_pr['body'] == pr_body
            and actual_pr['head']['sha'] == commit['sha']
            and actual_ref['object']['sha'] == commit['sha']
            and base64.b64decode(artifact['content']).decode() == content):
        raise RuntimeError('Remote publication verification failed')
    packet['handoff_status'] = 'published'
    return packet


def finalize(record, packet):
    published = packet.get('handoff_status') == 'published' and packet.get('issue_url') and packet.get('pr_url')
    completed = record['returncode'] == 0 and packet.get('status') == 'complete' and published
    record.update(state='complete' if completed else 'partial',
                  process_state='exited' if record['returncode'] == 0 else 'interrupted',
                  handoff_status=packet.get('handoff_status', 'pending'))
    return 0 if completed else 2
